import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

function writeArticle(body: string) {
  const dir = mkdtempSync(join(tmpdir(), 'article-business-readability-'));
  const file = join(dir, 'candidate.md');
  writeFileSync(file, body);
  return file;
}

function runCheck(file: string) {
  return execFileSync('node', ['scripts/article-business-readability-check.mjs', file, '--json'], {
    cwd: process.cwd(),
    encoding: 'utf8',
    stdio: 'pipe',
  });
}

function runCheckResult(file: string) {
  const result = spawnSync('node', ['scripts/article-business-readability-check.mjs', file, '--json'], {
    cwd: process.cwd(),
    encoding: 'utf8',
  });

  return {
    status: result.status,
    json: JSON.parse(result.stdout),
  };
}

describe('article business readability check', () => {
  it('rejects a draft that opens as a process-engineering workshop', () => {
    const candidate = writeArticle(
      [
        '# Заказы копятся быстрее, когда автоматизируют очередь',
        '',
        'Проведите 1 заказ через 4 передачи и найдите 2 очереди, где работа ждет человека. Такая карта покажет, нужен ли бот или сначала ясное правило.',
        '',
        'Форма на сайте стала удобнее. Уведомления приходят сразу. Клиенту больше не нужно ждать, пока менеджер перепишет сообщение в таблицу. Кажется, что заказы должны двигаться быстрее.',
        '',
        '## Проведите один заказ через четыре передачи',
        '',
        'Возьмите обычный завершенный заказ и отметьте каждую передачу, статус, владельца, исключение и правило следующего шага.',
        '',
        '## Статус обязан отвечать на следующий вопрос',
        '',
        'Хороший статус помогает принять решение без звонка автору строки.',
        '',
        '## Исключения показывают настоящую работу',
        '',
        'Исключение появляется, когда привычное правило не дает следующего шага.',
        '',
        '## Автоматизация нужна там, где правило уже можно проверить',
      ].join('\n'),
    );

    const result = runCheckResult(candidate);
    const issueCodes = result.json.issues.map((issue: { code: string }) => issue.code);

    expect(result.status).not.toBe(0);
    expect(issueCodes).toContain('lead_starts_with_workshop_instruction');
    expect(issueCodes).toContain('technical_heading_spine');
  });

  it('accepts a draft that starts with business pain before tools and process terms', () => {
    const candidate = writeArticle(
      [
        '# Заказы: где бизнес теряет деньги еще до оплаты',
        '',
        'Клиент оставил заявку утром и ждал ответ до вечера. Менеджер был уверен, что передал вопрос коллеге, коллега искал товар на складе, а руководитель узнал о задержке только после раздраженного звонка. Деньги еще не потеряны окончательно, но доверие уже стало дороже скидки.',
        '',
        'Такая история неприятна не из-за программы. Она показывает, что в компании есть место, где обещание клиенту перестает быть видимым для команды. Если заказов мало, это держится на памяти людей. Когда заявок становится больше, память превращается в риск для сроков, повторных продаж и оплаты.',
        '',
        'Автоматизация здесь нужна не как красивый экран. Сначала нужно понять, где именно клиент ждет, кто может вернуть заказ в движение и какую потерю бизнес хочет сократить.',
        '',
        '## День владельца начинается с чужих напоминаний',
        '',
        'Посмотрите на последние пять задержек и выпишите, кто первым заметил проблему: клиент, менеджер или руководитель.',
        '',
        '## Какая потеря повторяется чаще всего',
        '',
        'Отделите деньги, сроки и доверие клиента. У каждой потери будет свой первый шаг.',
        '',
        '## Что можно проверить за неделю',
        '',
        'Выберите один поток заказов и сравните, стало ли меньше ручных вопросов и забытых обещаний.',
      ].join('\n'),
    );

    const result = JSON.parse(runCheck(candidate));

    expect(result.pass).toBe(true);
    expect(result.metrics.early.businessSignals).toBeGreaterThan(result.metrics.early.technicalTerms);
  });

  it('rejects tool-agency phrasing like "CRM умеет собрать обращения"', () => {
    const candidate = writeArticle(
      [
        '# Заявки теряются между чатом и оплатой',
        '',
        'Клиент написал утром, менеджер ответил после обеда, а руководитель узнал о задержке только вечером. Заявка была рядом: в чате, в таблице и в памяти сотрудника. Но для бизнеса это уже потеря времени, доверия и шанса на оплату. Когда таких обращений становится больше, команда начинает спорить не о продажах, а о том, кто видел последнее сообщение.',
        '',
        'CRM умеет собрать обращения из формы, почты и мессенджера в один список. Но если команда не договорилась, кто первым отвечает клиенту и когда заказ считается принятым, список быстро превращается в ещё одно место для ручной проверки.',
        '',
        '## Где клиент ждет дольше всего',
        '',
        'Посмотрите на последние пять заявок и отметьте момент, когда клиент впервые остался без понятного ответа.',
        '',
        '## Что теряется до оплаты',
        '',
        'Отделите потерянное время, забытые обещания и скидки, которые пришлось дать из-за задержки.',
        '',
        '## Как переписать эту фразу',
        '',
        'В CRM можно собрать обращения из формы, почты и мессенджера в один список. Так фраза описывает настройку, а не человеческое умение программы.',
      ].join('\n'),
    );

    const result = runCheckResult(candidate);
    const issueCodes = result.json.issues.map((issue: { code: string }) => issue.code);

    expect(result.status).not.toBe(0);
    expect(issueCodes).toContain('tool_agency_phrasing');
  });

  it('does not flag a human role that includes a tool descriptor', () => {
    const candidate = writeArticle(
      [
        '# Доступы теряются между заявкой и оплатой',
        '',
        'Клиент ждет счет, менеджер просит открыть файл, а руководитель вечером выясняет, что доступ выдали не тому человеку. Для бизнеса это не техническая мелочь, а риск денег, сроков и доверия. Команда снова тратит время на переписку вместо продажи.',
        '',
        'Администратор системы не знает, какие поля реально нужны подрядчику. Это фраза про человека и его контекст, а не про человеческое умение программы.',
        '',
        'В системе можно ограничить права чтения, если заранее понятно, какие данные нужны для работы.',
        '',
        '## Где появляется лишний доступ',
        '',
        'Посмотрите последние пять заявок и отметьте, кто просил доступ, на какой срок и для какой задачи.',
        '',
        '## Что рискует увидеть подрядчик',
        '',
        'Отделите нужные поля от зарплатных данных, документов и реквизитов, которые не относятся к задаче.',
        '',
        '## Что проверить за неделю',
        '',
        'Выберите один тип запроса и сравните, стало ли меньше ручных уточнений и лишних прав.',
      ].join('\n'),
    );

    const result = JSON.parse(runCheck(candidate));

    expect(result.pass).toBe(true);
    expect(result.metrics.article.toolAgencyPhrases).toEqual([]);
  });
});
